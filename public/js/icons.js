const FALLBACK = { crop: "sprout", fruit: "Apple", node: "Stone", animal: "Egg" };
const cache = new Map();

function draw(shape, palette) {
  let rects = "";
  shape.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let w = 1;
      while (row[x + w] === ch) w++;
      if (ch !== "." && palette[ch]) rects += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${palette[ch]}"/>`;
      x += w;
    }
  });
  return rects;
}

// Devuelve un <svg> listo para insertar. name: recurso del juego o ícono de interfaz.
export function icon(name, { size = 24, category = null, cls = "" } = {}) {
  const key = SPRITES[name] ? name : FALLBACK[category] || "sprout";
  const cacheKey = `${key}|${size}|${cls}`;
  if (cache.has(cacheKey)) return cache.get(cacheKey);
  const [shape, palette] = SPRITES[key];
  const svg = `<svg class="px ${cls}" width="${size}" height="${size}" viewBox="0 0 10 10" shape-rendering="crispEdges" aria-hidden="true">${draw(SHAPES[shape], palette)}</svg>`;
  cache.set(cacheKey, svg);
  return svg;
}
